<?php

namespace Tests\Feature;

use PHPUnit\Framework\TestCase;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;

/** Accepted-worktree source proof only: no Laravel, environment, DB, HTTP or Git. */
class M77OwnedSharedSourceDeltaTest extends TestCase
{
    private const BASE = '5270494e0f999eee2a3d1fba6fb7c3f46a914481';
    private const FIXTURE_SHA = 'bf8544aa970b29400eecb903dd78151dbe7a908888d23842161b398916bd4b56';
    private const ROOTS = ['resources/views', 'resources/css', 'resources/js', 'public/js'];
    private const DISPATCH = [
        'app/Support/TheoryContentSource.php',
        'app/Support/TheoryHtmlAdapter.php',
        'app/Support/TheoryLegacyAdapter.php',
        'app/Support/TheoryContentRenderer.php',
        'app/Support/PracticeCompletionLinkedPractice.php',
        'app/Services/Theory/TextBlockToQuestionsMatcherService.php',
        'app/Services/TheoryCourseManifestService.php',
        'app/Http/Controllers/TestJsV2Controller.php',
    ];
    private const GENERIC = 'app/Support/TheoryBuilderSelectionPresentation.php';

    private static function root(): string
    {
        return str_replace('\\', '/', dirname(__DIR__, 2));
    }

    private static function read(string $relative): string
    {
        self::assertMatchesRegularExpression('~^(?:app|docs/content|database/content-patches|resources|public/js)/[A-Za-z0-9_./-]+$~D', $relative);
        self::assertStringNotContainsString('..', $relative);
        $path = self::root().'/'.$relative;
        self::assertFileExists($path);
        self::assertFalse(is_link($path));
        return file_get_contents($path);
    }

    private static function lf(string $bytes): string
    {
        return str_replace("\r\n", "\n", $bytes);
    }

    private static function fixture(): array
    {
        $path = self::root().'/tests/Fixtures/m77-owned-source-hunks.json';
        self::assertFileExists($path);
        self::assertFalse(is_link($path));
        self::assertSame(self::FIXTURE_SHA, hash_file('sha256', $path), 'Fixed independent source ledger, not regenerated by a test.');
        $ledger = json_decode(file_get_contents($path), true, flags: JSON_THROW_ON_ERROR);
        self::assertSame(1, $ledger['schema_version']);
        self::assertSame(self::BASE, $ledger['base_sha']);
        return $ledger;
    }

    public function test_twelve_finite_registrations_and_one_cardinality_hunk_reverse_to_complete_accepted_m76(): void
    {
        $ledger = self::fixture();
        self::assertSame([...self::DISPATCH, self::GENERIC], array_column($ledger['files'], 'path'));
        $dispatchHunks = $addedLines = $genericHunks = 0;
        foreach ($ledger['files'] as $file) {
            $raw = self::read($file['path']);
            $lf = self::lf($raw);
            self::assertSame($file['after_raw_sha256'], hash('sha256', $raw), $file['path'].' exact reviewed working bytes');
            self::assertSame($file['after_lf_sha256'], hash('sha256', $lf), $file['path'].' complete normalized source');
            $eol = $file['eol'] === 'CRLF' ? "\r\n" : "\n";
            if ($eol === "\r\n") {
                self::assertSame(substr_count($raw, "\n"), substr_count($raw, "\r\n"), 'No mixed/normalized controller or service EOL.');
            } else {
                self::assertStringNotContainsString("\r", $raw);
            }
            foreach ($file['hunks'] as $hunk) {
                self::assertNotSame('', $hunk['before']);
                self::assertNotSame('', $hunk['after']);
                self::assertSame(1, substr_count($lf, $hunk['after']), 'Each owned replacement is unique and exact.');
                if ($file['path'] !== self::GENERIC) {
                    ++$dispatchHunks;
                    self::assertSame('finite-package-registration', $file['kind']);
                    self::assertStringContainsString('M76', $hunk['before']);
                    self::assertStringNotContainsString('M77', $hunk['before']);
                    self::assertStringStartsWith($hunk['before'], $hunk['after']);
                    $addition = substr($hunk['after'], strlen($hunk['before']));
                    self::assertSame(1, substr_count($addition, "\n"));
                    self::assertStringContainsString('M77', $addition);
                    self::assertSame(1, count(array_filter(explode("\n", $addition), static fn ($line) => $line !== '')));
                    ++$addedLines;
                } else {
                    ++$genericHunks;
                    self::assertSame('owner-cardinality-generalization-owned-by-main', $file['kind']);
                    self::assertStringNotContainsString('M77', $hunk['after'], 'Common guard follows package owners, not a package-specific bypass.');
                    $restored = str_replace('$policy=static::policy();$ownerCount=count($package::OWNERS);', '$policy=static::policy();', $hunk['after']);
                    $restored = str_replace('|| $ownerCount<1 || count(', '|| count(', $restored);
                    self::assertSame(4, substr_count($restored, '!==$ownerCount'));
                    $restored = str_replace('!==$ownerCount', '!==3', $restored);
                    self::assertSame($hunk['before'], $restored, 'Only derive cardinality and reject an empty owner list; no selection, clone, snapshot, answer or formatter change.');
                }
                $lf = str_replace($hunk['after'], $hunk['before'], $lf);
                $raw = str_replace(str_replace("\n", $eol, $hunk['after']), str_replace("\n", $eol, $hunk['before']), $raw);
            }
            self::assertSame($file['base_lf_sha256'], hash('sha256', $lf), $file['path'].' complete accepted M76 source after only approved reversal');
            self::assertSame($file['working_before_raw_sha256'], hash('sha256', $raw), $file['path'].' exact initial checkout bytes/EOL recovered');
        }
        self::assertSame(12, $dispatchHunks);
        self::assertSame(12, $addedLines);
        self::assertSame(1, $genericHunks);
        self::assertSame($addedLines, $ledger['owned_added_registration_lines']);
    }

    public function test_standalone_object_guards_and_theory_only_selection_calls_stay_in_place(): void
    {
        $source = self::read('app/Support/TheoryContentSource.php');
        self::assertSame(1, substr_count($source, "[M77OnePrepositionsPhrasal::class, 'm42StyleContext']"));
        self::assertStringContainsString('if ($requiredContext !== null && !($context[$requiredContext] ?? false)) { continue; }', $source);
        $controller = self::read('app/Http/Controllers/TestJsV2Controller.php');
        foreach (['M76PronounRelations', 'M77OnePrepositionsPhrasal'] as $class) {
            self::assertSame(2, substr_count($controller, 'if ($block !== null) { $block = \\App\\Support\\'.$class.'::preserveExcludedTextBlock($block, \'standalone_test\'); }'));
            self::assertSame(2, substr_count($controller, 'if ($textBlock) { $textBlock = \\App\\Support\\'.$class.'::preserveExcludedTextBlock($textBlock, \'standalone_test\'); }'));
        }
        self::assertSame(1, substr_count(self::read('app/Services/TheoryCourseManifestService.php'), '$page = \\App\\Support\\M77OnePrepositionsPhrasal::preserveCoursePage($page);'));
        self::assertSame(1, substr_count(self::read('app/Support/TheoryContentRenderer.php'), '$bindings = M77BuilderSelectionPresentation::bindings($bindings);'));
        self::assertSame(1, substr_count(self::read('app/Support/PracticeCompletionLinkedPractice.php'), '$block = M77BuilderSelectionPresentation::matchingBlock($block, $canonicalTheory);'));
        self::assertSame(1, substr_count(self::read('app/Services/Theory/TextBlockToQuestionsMatcherService.php'), '$excludeQuestionIds = \\App\\Support\\M77BuilderSelectionPresentation::exclusions($block, $linkedPractice, $excludeQuestionIds);'));
        self::assertStringContainsString("if ((\$bindings['theoryCanonical'] ?? false) !== true)", self::read('app/Support/TheoryContentRenderer.php'));
    }

    public function test_all_326_visual_files_are_unchanged_including_approved_m76_bank_label(): void
    {
        $ledger = self::fixture();
        self::assertCount(326, $ledger['visual_sources']);
        $actual = [];
        foreach (self::ROOTS as $root) {
            $directory = self::root().'/'.$root;
            self::assertDirectoryExists($directory);
            self::assertFalse(is_link($directory));
            foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($directory, RecursiveDirectoryIterator::SKIP_DOTS)) as $file) {
                self::assertFalse($file->isLink());
                if ($file->isFile()) {
                    $actual[] = substr(str_replace('\\', '/', $file->getPathname()), strlen(self::root()) + 1);
                }
            }
        }
        $expected = array_column($ledger['visual_sources'], 'path');
        sort($actual, SORT_STRING);
        sort($expected, SORT_STRING);
        self::assertSame($expected, $actual, 'No M77 Blade, stylesheet, JS, formatter or generated visual file.');
        foreach ($ledger['visual_sources'] as $file) {
            $raw = self::read($file['path']);
            self::assertSame($file['working_before_raw_sha256'], hash('sha256', $raw), $file['path'].' raw before bytes preserved');
            self::assertSame($file['base_lf_sha256'], hash('sha256', self::lf($raw)), $file['path'].' accepted M76 design unchanged');
        }
        $widget = self::read('resources/views/components/text-block-practice-questions.blade.php');
        self::assertSame(1, substr_count($widget, 'x-text="Object.prototype.hasOwnProperty.call(currentQuestion?.token_labels ?? {}, token.value) && typeof currentQuestion.token_labels[token.value] === \'string\' ? currentQuestion.token_labels[token.value] : token.value"'));
        self::assertStringContainsString('x-text="token.value"', $widget, 'Selected answer chips still use actual values.');
    }

    public function test_previous_frozen_m76_releases_contract_and_global_page_controller_are_not_rewritten(): void
    {
        $ledger = self::fixture();
        self::assertCount(9, $ledger['immutable_sources']);
        foreach ($ledger['immutable_sources'] as $file) {
            $raw = self::read($file['path']);
            self::assertSame($file['working_before_raw_sha256'], hash('sha256', $raw), $file['path'].' exact initial working bytes');
            self::assertSame($file['base_lf_sha256'], hash('sha256', self::lf($raw)), $file['path'].' accepted historical artifact');
        }
        self::assertSame('app/Http/Controllers/PageController.php', $ledger['immutable_sources'][0]['path']);
        self::assertContains('docs/content/m76-token-label-display-fix.v1.json', array_column($ledger['immutable_sources'], 'path'));
    }
}
