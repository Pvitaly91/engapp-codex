    public function test_all_326_visual_source_bytes_and_existing_m76_every_shift_binding_are_unchanged(): void
    {
        $ledger = self::fixture(); self::assertCount(326, $ledger['visual_sources']);
        foreach (self::contexts($ledger) as $context) {
            $actual = [];
            foreach (self::ROOTS as $directory) {
                $path = $context['root'].'/'.$directory; self::assertDirectoryExists($path); self::assertFalse(is_link($path));
                foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($path, RecursiveDirectoryIterator::SKIP_DOTS)) as $file) {
                    self::assertFalse($file->isLink());
                    if ($file->isFile()) { $actual[] = substr(str_replace('\\', '/', $file->getPathname()), strlen($context['root']) + 1); }
                }
            }
            $expected = array_column($ledger['visual_sources'], 'path'); sort($actual, SORT_STRING); sort($expected, SORT_STRING);
            self::assertSame($expected, $actual, 'M78 adds no Blade, CSS, JS, formatter or visual source file.');
            foreach ($ledger['visual_sources'] as $file) {
                $raw = self::read($context['root'], $file['path']);
                self::assertSame($file[$context['profile'] === 'worktree' ? 'worktree_before_raw_sha256' : 'served_before_raw_sha256'], hash('sha256', $raw));
                if ($context['profile'] === 'worktree') { self::assertSame($file['accepted_m77_lf_sha256'], hash('sha256', self::lf($raw))); }
            }
            $widget = self::read($context['root'], 'resources/views/components/text-block-practice-questions.blade.php');
            self::assertSame(1, substr_count($widget, '&& items.every((item, index) => item.value === tokens[index])'));
            self::assertSame(1, substr_count($widget, 'items.push(items.shift());'));
            self::assertSame(1, substr_count($widget, 'x-text="Object.prototype.hasOwnProperty.call(currentQuestion?.token_labels ?? {}, token.value) && typeof currentQuestion.token_labels[token.value] === \'string\' ? currentQuestion.token_labels[token.value] : token.value"'));
            self::assertStringContainsString('x-text="token.value"', $widget);
        }
    }

    public function test_historical_m76_m77_sources_and_old_whole_file_tests_are_not_weakened(): void
    {
        $ledger = self::fixture(); self::assertCount(16, $ledger['immutable_sources']);
        $paths = array_column($ledger['immutable_sources'], 'path');
        self::assertContains('app/Support/TheoryBuilderSelectionPresentation.php', $paths);
        self::assertContains('tests/Feature/M77OwnedSharedSourceDeltaTest.php', $paths);
        self::assertContains('tests/Fixtures/m77-owned-source-hunks.json', $paths);
        self::assertNotContains('app/Support/ComposeTokenCase.php', $paths, 'The separately existing foreign ROOT formatter is not accepted-M77-equivalent.');
        foreach (self::contexts($ledger) as $context) {
            foreach ($ledger['immutable_sources'] as $file) {
                $raw = self::read($context['root'], $file['path']);
                self::assertSame($file[$context['profile'] === 'worktree' ? 'worktree_before_raw_sha256' : 'served_before_raw_sha256'], hash('sha256', $raw), $file['path']);
                self::assertSame($file['accepted_m77_lf_sha256'], hash('sha256', self::lf($raw)), $file['path']);
            }
        }
    }

    public function test_public_fixture_contains_only_source_hunks_paths_and_opaque_hashes(): void
    {
        $ledger = self::fixture();
        self::assertSame(['schema_version', 'base_sha', 'scope', 'independent_before_sha256', 'owned_added_registration_lines',
            'owned_validator_added_lines', 'owned_validator_removed_lines', 'files', 'visual_sources', 'immutable_sources'], array_keys($ledger));
        $json = json_encode($ledger, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES);
        self::assertDoesNotMatchRegularExpression('~(?:[A-Z]:[/\\\\]|storage/app/|password|DB_PASSWORD|APP_KEY|created_at|updated_at|runtime_identity|sql_before|question_snapshot)~', $json);
        foreach ($ledger['files'] as $file) {
            self::assertSame(['path', 'kind', 'accepted_m77_git_raw_sha256', 'accepted_m77_lf_sha256', 'hunks', 'profiles'], array_keys($file));
            self::assertSame(['worktree', 'served_root'], array_keys($file['profiles']));
            foreach ($file['hunks'] as $hunk) { self::assertSame(['before', 'after', 'added_lines', 'removed_lines'], array_keys($hunk)); }
            foreach ($file['profiles'] as $profile) {
                self::assertContains($profile['before_pin_origin'], ['independent-M78-BEFORE-shared-source-hash',
                    'explicit-main-pre-hunk-tool-observation-not-BEFORE-shared-source-inventory',
                    'accepted-M77-Git-LF-and-preserved-source-EOL-not-independent-ROOT-before-capture']);
                foreach (['before_raw_sha256', 'before_lf_sha256', 'after_raw_sha256', 'after_lf_sha256'] as $key) {
                    self::assertMatchesRegularExpression('/\A[a-f0-9]{64}\z/', $profile[$key]);
                }
            }
        }
        foreach ($ledger['visual_sources'] as $file) {
            self::assertSame(['path', 'accepted_m77_lf_sha256', 'worktree_before_raw_sha256', 'served_before_raw_sha256'], array_keys($file));
            foreach (array_diff_key($file, ['path' => true]) as $sha) { self::assertMatchesRegularExpression('/\A[a-f0-9]{64}\z/', $sha); }
        }
    }
