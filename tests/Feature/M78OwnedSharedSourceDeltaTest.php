        'app/Http/Controllers/TestJsV2Controller.php',
    ];
    private const VALIDATOR = 'app/Support/TheoryNativeContentRelease.php';
    private const FOREIGN = ['app/Services/TheoryCourseManifestService.php', 'app/Http/Controllers/TestJsV2Controller.php'];

    private static function root(): string
    {
        return str_replace('\\', '/', dirname(__DIR__, 2));
    }

    private static function read(string $root, string $relative): string
    {
        self::assertMatchesRegularExpression('~^(?:app|docs/content|database/content-patches|resources|public/js|tests)/[A-Za-z0-9_./-]+$~D', $relative);
        self::assertStringNotContainsString('..', $relative);
        $path = $root.'/'.$relative;
        self::assertFileExists($path); self::assertFalse(is_link($path));
        return file_get_contents($path);
    }

    private static function lf(string $raw): string
    {
        return str_replace("\r\n", "\n", $raw);
    }

    private static function fixture(): array
    {
        $file = self::root().'/tests/Fixtures/m78-owned-source-hunks.json';
        self::assertFileExists($file); self::assertFalse(is_link($file));
        self::assertSame(self::FIXTURE_SHA, hash_file('sha256', $file), 'Reviewed source-only ledger cannot be regenerated by a test.');
        $ledger = json_decode(file_get_contents($file), true, flags: JSON_THROW_ON_ERROR);
        self::assertSame(1, $ledger['schema_version']); self::assertSame(self::BASE, $ledger['base_sha']);
        self::assertSame(self::BEFORE_SHA, $ledger['independent_before_sha256']);
        return $ledger;
    }

    /** ROOT is optional and explicit; its foreign-inclusive profile is never equated with WT. */
    private static function contexts(array $ledger): array
    {
        $roots = [self::root()];
        $served = getenv('GRAMLYZE_M78_SERVED_ROOT');
        if (is_string($served) && $served !== '') {
            self::assertMatchesRegularExpression('~^(?:[A-Za-z]:[/\\\\]|/)~', $served);
            self::assertDirectoryExists($served); self::assertFalse(is_link($served));
            $served = str_replace('\\', '/', rtrim($served, '/\\'));
            if ($served !== self::root()) { $roots[] = $served; }
        }
        $controller = $ledger['files'][7];
        self::assertSame(self::DISPATCH[7], $controller['path']);
        $contexts = [];
        foreach ($roots as $root) {
            $sha = hash('sha256', self::read($root, $controller['path']));
            $profiles = array_keys(array_filter($controller['profiles'], static fn ($p) => $p['after_raw_sha256'] === $sha));
            self::assertCount(1, $profiles, 'An exact whole-file ROOT or WT profile is required.');
            $contexts[] = ['root' => $root, 'profile' => $profiles[0]];
        }
        return $contexts;
    }

    public function test_twelve_dispatch_lines_and_source_validator_reverse_to_exact_predecessor_profiles(): void
    {
        $ledger = self::fixture();
        self::assertSame([...self::DISPATCH, self::VALIDATOR], array_column($ledger['files'], 'path'));
        foreach (self::contexts($ledger) as $context) {
            $dispatchHunks = $validatorHunks = $added = $removed = 0;
            foreach ($ledger['files'] as $file) {
                $profile = $file['profiles'][$context['profile']];
                $raw = self::read($context['root'], $file['path']); $lf = self::lf($raw);
                self::assertSame($profile['after_raw_sha256'], hash('sha256', $raw), $file['path'].' exact complete working profile');
                self::assertSame($profile['after_lf_sha256'], hash('sha256', $lf));
                self::assertSame($profile['after_lf_line_count'], substr_count($raw, "\n"));
                self::assertSame($profile['after_crlf_line_count'], substr_count($raw, "\r\n"));
                if ($profile['eol'] === 'mixed-preserved') {
                    self::assertSame('served_root', $context['profile']);
                    self::assertSame('app/Services/TheoryCourseManifestService.php', $file['path']);
                }
                foreach ($file['hunks'] as $i => $hunk) {
                    self::assertNotSame('', $hunk['before']); self::assertNotSame('', $hunk['after']);
                    self::assertSame(1, substr_count($lf, $hunk['after']), 'An owned hunk must have one exact source occurrence.');
                    $lf = str_replace($hunk['after'], $hunk['before'], $lf);
                    if ($file['path'] !== self::VALIDATOR) {
                        ++$dispatchHunks;
                        self::assertSame('finite-package-registration', $file['kind']);
                        self::assertStringContainsString('M77', $hunk['before']); self::assertStringNotContainsString('M78', $hunk['before']);
                        self::assertStringStartsWith($hunk['before'], $hunk['after']);
                        $addition = substr($hunk['after'], strlen($hunk['before']));
                        self::assertSame(1, substr_count($addition, "\n")); self::assertStringContainsString('M78', $addition);
                        self::assertSame(1, $hunk['added_lines']); self::assertSame(0, $hunk['removed_lines']);
                        $eol = $profile['hunk_added_line_eols'][$i]; self::assertContains($eol, ['LF', 'CRLF']);
                        $rawAddition = $eol === 'CRLF' ? str_replace("\n", "\r\n", $addition) : $addition;
                        self::assertSame(1, substr_count($raw, $rawAddition));
                        $raw = str_replace($rawAddition, '', $raw);
                    } else {
                        ++$validatorHunks; $added += $hunk['added_lines']; $removed += $hunk['removed_lines'];
                        self::assertSame('captured-native-task-identity-preservation-source-validator-only', $file['kind']);
                        self::assertSame('LF', $profile['hunk_added_line_eols'][$i]); self::assertStringNotContainsString("\r", $raw);
                        self::assertSame(1, substr_count($raw, $hunk['after'])); $raw = str_replace($hunk['after'], $hunk['before'], $raw);
                    }
                }
                self::assertSame($profile['before_raw_sha256'], hash('sha256', $raw), $file['path'].' complete raw predecessor restored without EOL normalization');
                self::assertSame($profile['before_lf_sha256'], hash('sha256', $lf));
                if ($context['profile'] === 'worktree' || !in_array($file['path'], self::FOREIGN, true)) {
                    self::assertSame($file['accepted_m77_lf_sha256'], hash('sha256', $lf), 'Only owned M78 changes differ from accepted M77.');
                } else {
                    self::assertNotSame($file['profiles']['worktree']['before_raw_sha256'], hash('sha256', $raw), 'The captured foreign ROOT raw predecessor must not be flattened into WT.');
                    if ($file['path'] === 'app/Http/Controllers/TestJsV2Controller.php') {
                        self::assertNotSame($file['accepted_m77_lf_sha256'], hash('sha256', $lf), 'Foreign controller learning behavior remains present.');
                    } else {
                        self::assertSame($file['accepted_m77_lf_sha256'], hash('sha256', $lf), 'Course profile differs only in preserved mixed line endings.');
                    }
                    self::assertSame('independent-M78-BEFORE-shared-source-hash', $profile['before_pin_origin']);
                }
            }
            self::assertSame(12, $dispatchHunks); self::assertSame(4, $validatorHunks);
            self::assertSame(27, $added); self::assertSame(4, $removed);
            self::assertSame($dispatchHunks, $ledger['owned_added_registration_lines']);
            self::assertSame($added, $ledger['owned_validator_added_lines']); self::assertSame($removed, $ledger['owned_validator_removed_lines']);
        }
    }

